#!/usr/bin/env python3
"""Generate the public placeholder character pack and demo background."""

from __future__ import annotations

import json
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "character_packs" / "placeholder"
S = 4  # supersample for anti-aliased edges

PAPER = "#F5F0E6"
INK = "#2B2B2B"
HAIR = "#7B82B8"
HAIR_DARK = "#4E537D"
SKIN = "#EED0B8"
COAT = "#B18E62"
COAT_DARK = "#8C6D4C"
IVORY = "#E9E0CE"
DARK = "#2A2930"


def canvas(width: int, height: int, color: tuple[int, int, int, int] = (0, 0, 0, 0)):
    image = Image.new("RGBA", (width * S, height * S), color)
    return image, ImageDraw.Draw(image)


def scaled_box(x0, y0, x1, y1):
    return [x0 * S, y0 * S, x1 * S, y1 * S]


def draw_character() -> Image.Image:
    image, draw = canvas(1080, 1920)

    # braids behind the body
    for x in (300, 780):
        points = [(x * S, 640 * S), ((x - 40) * S, 1150 * S), (x * S, 1600 * S)]
        draw.line(points, fill=HAIR_DARK, width=52 * S, joint="curve")
        draw.line(points, fill=HAIR, width=38 * S, joint="curve")
        draw.ellipse(scaled_box(x - 30, 1580, x + 30, 1640), fill=DARK)

    # arms behind the coat
    draw.line(
        [(400 * S, 820 * S), (330 * S, 1200 * S)],
        fill=COAT,
        width=70 * S,
    )
    draw.line(
        [(680 * S, 820 * S), (750 * S, 1200 * S)],
        fill=COAT,
        width=70 * S,
    )

    # legs behind the boots
    for x in (460, 560):
        draw.rounded_rectangle(
            scaled_box(x, 1300, x + 60, 1830), radius=20 * S, fill=IVORY,
            outline=INK, width=4 * S,
        )

    # boots
    for x in (455, 565):
        draw.rounded_rectangle(
            scaled_box(x, 1740, x + 70, 1920), radius=18 * S, fill=IVORY,
            outline=INK, width=4 * S,
        )

    # coat / body
    draw.polygon(
        [
            (390 * S, 760 * S),
            (690 * S, 760 * S),
            (730 * S, 1380 * S),
            (350 * S, 1380 * S),
        ],
        fill=COAT,
        outline=INK,
    )
    draw.polygon(
        [
            (470 * S, 760 * S),
            (610 * S, 760 * S),
            (590 * S, 1290 * S),
            (490 * S, 1290 * S),
        ],
        fill=IVORY,
        outline=INK,
    )
    draw.polygon(
        [(520 * S, 800 * S), (560 * S, 800 * S), (540 * S, 1180 * S)],
        fill=DARK,
        outline=INK,
    )
    # belt
    draw.rectangle(scaled_box(420, 1290, 660, 1335), fill=COAT_DARK, outline=INK, width=4 * S)

    # head + hair
    draw.ellipse(scaled_box(400, 480, 680, 800), fill=HAIR, outline=INK, width=4 * S)
    draw.ellipse(scaled_box(435, 520, 645, 750), fill=SKIN, outline=INK, width=4 * S)
    draw.ellipse(scaled_box(470, 590, 500, 620), fill=INK)
    draw.ellipse(scaled_box(580, 590, 610, 620), fill=INK)

    # witch hat
    draw.ellipse(scaled_box(180, 420, 900, 560), fill=DARK, outline=INK, width=5 * S)
    draw.polygon(
        [(540 * S, 90 * S), (330 * S, 470 * S), (750 * S, 470 * S)],
        fill=DARK,
        outline=INK,
    )
    draw.rectangle(scaled_box(330, 400, 750, 455), fill=IVORY, outline=INK, width=4 * S)

    return image.resize((1080, 1920), Image.LANCZOS)


def draw_background() -> Image.Image:
    image = Image.new("RGB", (1920, 1080), PAPER)
    draw = ImageDraw.Draw(image)
    for x in range(0, 1920, 80):
        draw.line([(x, 0), (x, 1080)], fill=(238, 232, 220), width=1)
    for y in range(0, 1080, 80):
        draw.line([(0, y), (1920, y)], fill=(238, 232, 220), width=1)
    return image


def draw_floor() -> Image.Image:
    image = Image.new("RGB", (1920, 300), "#C9A876")
    draw = ImageDraw.Draw(image)
    for i in range(0, 300, 36):
        draw.line([(0, i), (1920, i)], fill="#B08E5E", width=4)
    for x in range(0, 1920, 260):
        draw.line([(x, 0), (x, 300)], fill="#B08E5E", width=3)
    return image


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    draw_character().save(OUT / "character.png")
    draw_background().save(OUT / "background.png")
    draw_floor().save(OUT / "floor.png")
    manifest = {
        "name": "placeholder",
        "display_name": "Placeholder Pack",
        "version": 1,
        "canvas": [1080, 1920],
        "anchor": {"x": 0.5, "y": 0},
        "source": "generated by scripts/make_placeholder_pack.py",
        "license": "public domain placeholder; no copyrighted character",
        "assets": [
            {
                "id": "placeholder_character",
                "file": "character.png",
                "expression": "neutral",
                "pose": "standing",
                "variant": 1,
            }
        ],
    }
    (OUT / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"placeholder pack written to {OUT}")


if __name__ == "__main__":
    main()
